<h2>Política de Privacidade e Uso do Hotspot</h2>
<p>Esta política descreve como a FIRENETWORK trata os dados pessoais de visitantes e clientes que utilizam o hotspot FireSpot, em conformidade com a Lei Geral de Proteção de Dados (LGPD – Lei nº 13.709/2018) e demais normas aplicáveis.</p>

<h3>1. Dados coletados</h3>
<p>Coletamos apenas o necessário para liberar e manter a sua conexão:</p>
<ul>
  <li>Identificadores pessoais informados pelo usuário (CPF, nome, e-mail, telefone) quando exigidos pelo fluxo de cadastro ou validação.</li>
  <li>Credenciais de autenticação geradas pelo sistema (usuário e senha temporária ou permanente).</li>
  <li>Informações técnicas da conexão registradas automaticamente (endereço IP, MAC, dispositivo, horário de acesso, volume de dados, sessões RADIUS accounting).</li>
  <li>Preferências opcionais, como consentimento de marketing e histórico de QR Codes de parceiros.</li>
</ul>

<h3>2. Finalidades do tratamento</h3>
<p>Os dados são utilizados para:</p>
<ul>
  <li>Autenticar o usuário na rede Wi-Fi e aplicar o plano contratado ou promocional.</li>
  <li>Manter registros de conexão exigidos pela legislação brasileira e por órgãos reguladores.</li>
  <li>Prevenir fraudes, garantir segurança da rede e controlar limites de uso.</li>
  <li>Realizar atendimento e suporte técnico quando solicitado.</li>
  <li>Enviar comunicações operacionais e, apenas com consentimento específico, mensagens comerciais.</li>
</ul>

<h3>3. Bases legais</h3>
<p>Tratamos dados com fundamento em bases legais previstas na LGPD, como execução de contrato (art. 7º, V), cumprimento de obrigação legal ou regulatória (art. 7º, II), legítimo interesse (art. 7º, IX) e consentimento (art. 7º, I) quando aplicável.</p>

<h3>4. Compartilhamento</h3>
<p>Os dados podem ser compartilhados com:</p>
<ul>
  <li>Provedores de infraestrutura (por exemplo, autenticação RADIUS, sistemas de bilhetagem) estritamente para operação do serviço.</li>
  <li>Autoridades públicas mediante requisição formal ou cumprimento de obrigação legal.</li>
  <li>Parceiros comerciais, apenas quando necessário para liberar benefícios vinculados a QR Codes ou promoções e sempre limitados ao mínimo indispensável.</li>
</ul>

<h3>5. Retenção</h3>
<p>Dados cadastrais e registros de conexão são mantidos pelo período necessário para execução do serviço e cumprimento de obrigações legais. Passado o prazo regulatório, são eliminados ou anonimizados com segurança.</p>

<h3>6. Segurança</h3>
<p>Adotamos medidas técnicas e administrativas de segurança, incluindo controle de acesso, criptografia de senhas, monitoramento de tentativas suspeitas e isolamento dos bancos de dados, para proteger seus dados contra acessos não autorizados.</p>

<h3>7. Direitos do titular</h3>
<p>Você pode exercer os direitos previstos na LGPD (confirmação, acesso, correção, anonimização, portabilidade, eliminação, revogação de consentimento, oposição) enviando solicitação para <a href="mailto:firespot@firenetwork.com.br">firespot@firenetwork.com.br</a>. Responderemos dentro dos prazos legais.</p>

<h3>8. Cookies e identificadores</h3>
<p>Utilizamos cookies e identificadores locais apenas para manter a sessão ativa e facilitar o reconhecimento do dispositivo. É possível gerenciar cookies no navegador, porém a remoção pode impactar o login automático.</p>

<h3>9. Publicidade e acesso patrocinado</h3>
<p>Em telas não transacionais, o portal pode apresentar publicidade administrada pela FireSpot. Campanhas diretas têm prioridade e o Google Ad Manager pode preencher espaços remanescentes. O checkout, a confirmação de pagamento e a liberação de um acesso comprado não dependem de anúncio.</p>
<p>Quando houver acesso gratuito patrocinado, a quantidade de anúncios e o tempo concedido são informados antes do início. Participar é opcional, nenhum clique é exigido e fechar o anúncio antes da conclusão não gera a recompensa. A receita da demanda Google pertence à FireSpot, salvo contrato expresso em sentido diferente.</p>
<p>Anúncios não personalizados ou limitados são o padrão enquanto não houver uma decisão válida de consentimento. O provedor pode receber sinais técnicos estritamente necessários para entrega, medição, segurança e combate a tráfego inválido, observadas suas políticas e a legislação aplicável.</p>

<h3>10. Atualizações</h3>
<p>Podemos atualizar estes termos para refletir novas funcionalidades, exigências legais ou ajustes no serviço. Mudanças relevantes serão comunicadas nos canais oficiais e a nova versão passa a valer a partir da data indicada.</p>

